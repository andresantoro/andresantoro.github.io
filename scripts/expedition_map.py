"""Draw the expedition map shown in the /cv/ title band (_includes/nb/cv-map.svg).

The coastline comes from Natural Earth's 1:50m land polygons (public domain,
https://www.naturalearthdata.com/downloads/50m-physical-vectors/), clipped to Western
Europe and simplified; the route joins the cities of the CV in order. Styling lives in
assets/css/notebook.scss (.nb-map).

    python3 scripts/expedition_map.py path/to/ne_50m_land.shp

Requires: pyshp, shapely.
"""

import math
import sys
from pathlib import Path

import shapefile
from shapely.geometry import box, shape

OUT = Path(__file__).resolve().parent.parent / "_includes" / "nb" / "cv-map.svg"

LON0, LON1, LAT0, LAT1 = -5.5, 18.6, 36.4, 53.4
W = 360
KX = math.cos(math.radians(46))
SCALE = W / ((LON1 - LON0) * KX)
H = round((LAT1 - LAT0) * SCALE)

# (city, lon, lat, years, label side)
STOPS = [
    ("Catania", 15.09, 37.50, "2011", "left"),
    ("London", -0.04, 51.52, "2016", "left"),
    ("Geneva", 6.15, 46.20, "2021", "left"),
    ("Turin", 7.69, 45.07, "2024", "right"),
]
# bends of the dashed route between consecutive stops (control point offsets, in px)
BENDS = [(-70, 10), (60, -30), (30, 26)]


def xy(lon, lat):
    return (lon - LON0) * KX * SCALE, (LAT1 - lat) * SCALE


def ring(coords):
    pts = [xy(x, y) for x, y in coords]
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"


def main(shp):
    clip = box(LON0 - 1, LAT0 - 1, LON1 + 1, LAT1 + 1)
    paths = []
    for rec in shapefile.Reader(shp).shapes():
        g = shape(rec.__geo_interface__).intersection(clip)
        if g.is_empty:
            continue
        g = g.simplify(0.06, preserve_topology=True)
        for p in getattr(g, "geoms", [g]):
            if p.geom_type != "Polygon" or p.area < 0.05:
                continue
            paths.append(ring(p.exterior.coords))
    land = " ".join(paths)

    grat = []
    for lon in range(-5, 20, 5):
        x, _ = xy(lon, 0)
        grat.append(f"M{x:.1f} 0V{H}")
    for lat in range(40, 56, 5):
        _, y = xy(0, lat)
        grat.append(f"M0 {y:.1f}H{W}")

    pts = [xy(lon, lat) for _, lon, lat, _, _ in STOPS]
    route = f"M{pts[0][0]:.1f} {pts[0][1]:.1f}"
    for (a, b), (dx, dy) in zip(zip(pts, pts[1:]), BENDS):
        cx, cy = (a[0] + b[0]) / 2 + dx, (a[1] + b[1]) / 2 + dy
        route += f" Q{cx:.1f} {cy:.1f} {b[0]:.1f} {b[1]:.1f}"

    # the Alps, as a row of little peaks along the arc east of Turin (the western peaks would crowd the labels)
    alps = []
    for lon, lat, s in [(9.0, 46.6, 8), (10.4, 46.9, 9), (11.8, 47.1, 8), (13.2, 47.2, 7), (14.5, 47.4, 6)]:
        x, y = xy(lon, lat)
        alps.append(f"M{x - s:.1f} {y + s * 0.6:.1f}L{x:.1f} {y - s * 0.7:.1f}L{x + s:.1f} {y + s * 0.6:.1f}")
        alps.append(f"M{x - s * 0.3:.1f} {y - s * 0.32:.1f}L{x:.1f} {y - s * 0.05:.1f}L{x + s * 0.3:.1f} {y - s * 0.32:.1f}")

    stops = []
    for i, ((name, _, _, year, side), (x, y)) in enumerate(zip(STOPS, pts)):
        now = i == len(STOPS) - 1
        tx = x + 13 if side == "right" else x - 13
        anchor = "start" if side == "right" else "end"
        stops.append(
            f'  <g class="nb-map__stop{" is-now" if now else ""}" style="--i: {i}">'
            f'<path class="nb-map__pin" d="M{x:.1f} {y - 6.5:.1f}l6.5 6.5-6.5 6.5-6.5-6.5z" />'
            f'<text x="{tx:.1f}" y="{y - 1:.1f}" text-anchor="{anchor}">{name}</text>'
            f'<text class="nb-map__year" x="{tx:.1f}" y="{y + 12:.1f}" text-anchor="{anchor}">{year}</text></g>'
        )
    tx, ty = pts[-1]
    flag = f'M{tx:.1f} {ty - 7:.1f}v-22 M{tx + 0.8:.1f} {ty - 28.5:.1f}h12l-3.2 4.2 3.2 4.3h-12z'

    # sea marks
    waves = []
    for lon, lat in [(-3.6, 46.2), (4.4, 42.4), (9.4, 39.6), (17.2, 41.2), (2.6, 52.9)]:
        x, y = xy(lon, lat)
        waves.append(f"M{x - 9:.1f} {y:.1f}q4.5 -4 9 0t9 0")

    cx, cy = W - 34, 34
    rose = (f'M{cx} {cy - 20}L{cx + 4} {cy}L{cx} {cy + 20}L{cx - 4} {cy}Z '
            f'M{cx - 20} {cy}L{cx} {cy - 4}L{cx + 20} {cy}L{cx} {cy + 4}Z')

    svg = f"""<svg class="nb-map__svg" viewBox="0 0 {W} {H}" role="img" aria-labelledby="nb-map-t" focusable="false">
  <title id="nb-map-t">Map of the route so far: Catania (2011), London (2016), Geneva (2021) and Turin (2024), where camp is now.</title>
  <!-- generated by scripts/expedition_map.py; coastline from Natural Earth (public domain) -->
  <path class="nb-map__grat" d="{' '.join(grat)}" />
  <path class="nb-map__land" d="{land}" />
  <path class="nb-map__wave" d="{' '.join(waves)}" />
  <path class="nb-map__alps" d="{' '.join(alps)}" />
  <path class="nb-map__rose" d="{rose}" /><text class="nb-map__n" x="{cx}" y="{cy - 25}">N</text>
  <path class="nb-map__route" d="{route}" />
{chr(10).join(stops)}
  <path class="nb-map__flag" d="{flag}" />
</svg>
"""
    OUT.write_text(svg)
    print(f"wrote {OUT} ({W}x{H}, {len(paths)} land polygons)")


if __name__ == "__main__":
    main(sys.argv[1])
